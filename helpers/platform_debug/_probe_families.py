async def main():
    async with async_session_factory() as s:
        for fam, pats in FAMILIES.items():
            if not pats:
                continue
            cond = " or ".join(f"lower(description) like :p{i}" for i in range(len(pats)))
            q = text(
                f"select count(*), min(description) "
                f"from oe_costs_item where is_active and ({cond})")
            params = {f"p{i}": f"%{p}%" for i, p in enumerate(pats)}
            n, sample = (await s.execute(q, params)).fetchone()
            ex = (sample or "")[:70]
            print(f"{fam:42} {n:>5}  ex: {ex}")


asyncio.run(main())
